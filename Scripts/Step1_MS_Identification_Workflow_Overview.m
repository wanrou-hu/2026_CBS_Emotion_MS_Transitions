%% ============================================================
% MS Identification Workflow Overview
%
% Toolbox: EEGLAB + Microstate Analysis Toolbox (MST1.0)
%
% Purpose:
%   1. First-step clustering within individual trials
%   2. Second-step clustering of pooled candidate topographies
%   3. Final MS class determination
%   4. Individual-level back-fitting and statistics extraction
%
% Note:
%   This script documents the analysis workflow and key parameters.
%% ============================================================


%% ============================================================
% 1. First-step clustering: within-trial clustering
%% ============================================================
% Select GFP-peak topographies for microstate analysis:
[EEG, ALLEEG] = pop_micro_selectdata(EEG, ALLEEG, ...
    'datatype', 'spontaneous', ...
    'avgref', 0, ...
    'normalise', 1, ...
    'MinPeakDist', 10, ...
    'Npeaks', 10000, ...
    'GFPthresh', 1, ...
    'dataset_idx', []);

% Identify candidate microstate prototypes using modified k-means:
EEG = pop_micro_segment(EEG, ...
    'algorithm', 'modkmeans', ...
    'sorting', 'Global explained variance', ...
    'normalise', 1, ...
    'Nmicrostates', 3:8, ...
    'verbose', 1, ...
    'Nrepetitions', 1000, ...
    'fitmeas', 'CV', ...
    'max_iterations', 5000, ...
    'threshold', 1e-6, ...
    'optimised', 1);

% Extract trial-level candidate prototypes
% Candidate solutions are evaluated across k = 3:8.
% The CV criterion is used to identify the preferred
% number of microstates for each trial.


%% ============================================================
% 2. Second-step clustering: group-level template identification
%% ============================================================
% Pool candidate topographies from the first-step clustering:
candidate_topographies = [candidate1_topographies, ...
                          candidateN_topographies];

% Perform group-level clustering:
EEG = pop_micro_segment(EEG, ...
    'algorithm', 'modkmeans', ...
    'sorting', 'Global explained variance', ...
    'normalise', 0, ...
    'Nmicrostates', 3:8, ...
    'verbose', 1, ...
    'Nrepetitions', 10000, ...
    'fitmeas', 'CV', ...
    'max_iterations', 5000, ...
    'threshold', 1e-6, ...
    'optimised', 1);


%% ============================================================
% 3. Final MS class determination
%% ============================================================
% Evaluate candidate group-level solutions using CV and GEV:
data_MS = pop_micro_selectNmicro(EEG, ...
    'Measures', {'CV', 'GEV'}, ...
    'Nmicro', [], ...
    'do_subplots', [0, 1]);


%% ============================================================
% 4. Individual-level back-fitting
%% ============================================================
% Import the final group-level templates:
EEG.microstate.prototypes = final_templates;

% Assign each EEG time point to the best-matching microstate:
EEG = pop_micro_fit(EEG, 'polarity', 0);

% Apply temporal smoothing to the back-fitted labels:
EEG = pop_micro_smooth(EEG, ...
    'label_type', 'backfit', ...
    'smooth_type', 'reject segments', ...
    'minTime', 30, ...
    'polarity', 0);


%% ============================================================
% 5. Microstate statistics extraction
%% ============================================================
% Calculate microstate statistics from back-fitted labels:
EEG = pop_micro_stats(EEG, ...
    'label_type', 'backfit', ...
    'polarity', 0);
